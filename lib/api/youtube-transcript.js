/**
 * YouTube Transcript API — public captions for any video that has them.
 *
 * Reads only public caption data. No stream URL is resolved, no access control
 * is circumvented, and a video without captions is reported as such rather
 * than faked.
 *
 *   POST /api/youtube-transcript
 *   { url | videoId, lang?: 'en', format?: 'text'|'json'|'srt'|'vtt'|'chapters', includeMeta?: bool }
 *
 *   GET  /api/youtube-transcript?url=…&lang=en&format=srt
 */
import {
  extractVideoId, fetchPlayer, fetchTrackText, fetchViaPiped, parseCaptions,
  toSrt, toVtt, chaptersFromDescription
} from '../ai-mode/youtube.js';
import { sendJSON, readJSONBody, createLimiter, createCache } from '../ai-mode/http.js';

const limited = createLimiter({ max: 45, windowMs: 60_000 });
const cache = createCache({ ttlMs: 30 * 60_000, max: 200 });

export function buildResult({ player, segments, track, source }) {
  const text = segments.map(s => s.text).join(' ').replace(/\s+/g, ' ').trim();
  const last = segments[segments.length - 1];
  return {
    ok: true,
    videoId: player.videoId,
    title: player.title || '',
    author: player.author || '',
    channelUrl: player.channelId ? `https://www.youtube.com/channel/${player.channelId}` : null,
    url: `https://www.youtube.com/watch?v=${player.videoId}`,
    thumbnail: player.thumbnail || null,
    duration: last ? Math.round(last.start + (last.duration || 0)) : player.lengthSeconds || 0,
    durationSeconds: player.lengthSeconds || null,
    viewCount: player.viewCount,
    publishDate: player.publishDate,
    language: track?.languageCode || 'en',
    languageName: track?.name?.simpleText || track?.name?.runs?.[0]?.text || track?.languageCode || 'English',
    isAutoGenerated: track?.kind === 'asr' || String(track?.vssId || '').startsWith('a.'),
    segments,
    text,
    count: segments.length,
    words: text ? text.split(/\s+/).length : 0,
    chapters: chaptersFromDescription(player.description),
    source,
    retrieved: new Date().toISOString()
  };
}

/** The whole retrieval chain, exported so tests can drive it with a stub fetch. */
export async function getTranscript(input, { fetchImpl = fetch, lang = 'en' } = {}) {
  const videoId = extractVideoId(input);
  if (!videoId) return { ok: false, status: 400, error: 'Enter a valid YouTube video URL or 11-character video ID.' };

  const player = await fetchPlayer(videoId, { fetchImpl, lang });
  const attempts = [];

  if (player.ok && player.captionTracks?.length && player.track) {
    const got = await fetchTrackText(player.track.baseUrl, { fetchImpl });
    attempts.push(`innertube:${player.track.languageCode}`);
    if (got?.segments?.length) {
      return buildResult({ player, segments: got.segments, track: player.track, source: 'youtube-captions' });
    }
  } else if (!player.ok) {
    attempts.push(`innertube:${player.error}`);
  } else {
    attempts.push('innertube:no-caption-tracks');
  }

  // Public mirror fallback (same public caption data, different host).
  const piped = await fetchViaPiped('video', videoId, { fetchImpl });
  if (piped.ok) {
    const subs = piped.data?.subtitles || [];
    const track = subs.find(s => s.code === lang) || subs.find(s => String(s.code).startsWith(lang)) || subs[0];
    if (track?.url) {
      const got = await fetchTrackText(track.url, { fetchImpl });
      if (got?.segments?.length) {
        return buildResult({
          player: {
            ...player,
            ok: true,
            videoId,
            title: player.title || piped.data?.title || '',
            author: player.author || piped.data?.uploader || '',
            channelId: player.channelId || '',
            description: player.description || piped.data?.description || '',
            thumbnail: player.thumbnail || piped.data?.thumbnailUrl || null
          },
          segments: got.segments,
          track: { languageCode: track.code || lang, name: { simpleText: track.name || track.code || lang } },
          source: 'piped'
        });
      }
    }
    attempts.push('piped:no-captions');
  } else {
    attempts.push('piped:unreachable');
  }

  const detail = player.ok
    ? 'This video publishes no caption track, or its captions are restricted to signed-in viewers.'
    : `YouTube returned “${player.error}” for this video.`;
  return {
    ok: false,
    status: 404,
    error: `${detail} AI Mode only reads public captions — it will not bypass a platform control.`,
    videoId,
    attempts,
    hint: 'Works for videos with manual or auto-generated captions. Very new uploads, region-locked videos and music-licence-restricted videos often have none.'
  };
}

export default async function handler(req, res) {
  if (req.method === 'OPTIONS') {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
    res.statusCode = 204;
    return res.end();
  }
  if (req.method !== 'POST' && req.method !== 'GET') return sendJSON(res, 405, { error: 'GET or POST only.' });
  if (limited(req)) return sendJSON(res, 429, { error: 'Too many transcript lookups. Wait a minute.' });

  const url = new URL(req.url || '/api/youtube-transcript', 'https://megaplan.invalid');
  const body = req.method === 'POST' ? readJSONBody(req) : Object.fromEntries(url.searchParams);
  const input = body.url || body.videoId || body.link || body.v;
  const lang = String(body.lang || 'en').toLowerCase().slice(0, 5);
  const format = String(body.format || 'text').toLowerCase();
  if (!input) return sendJSON(res, 400, { error: 'Enter a YouTube URL or video ID.' });

  const videoId = extractVideoId(input);
  const key = `yt:${videoId}:${lang}`;
  const cached = cache.get(key);
  const result = cached || await getTranscript(input, { lang });
  if (!cached && result.ok) cache.set(key, result);
  if (!result.ok) return sendJSON(res, result.status || 502, result);

  if (format === 'srt') result.srt = toSrt(result.segments);
  else if (format === 'vtt') result.vtt = toVtt(result.segments);
  else if (format === 'chapters') {
    return sendJSON(res, 200, {
      ok: true,
      videoId: result.videoId,
      title: result.title,
      chapters: result.chapters.length ? result.chapters : deriveChapters(result.segments),
      source: result.source
    });
  }
  if (body.includeMeta === false) {
    const { segments, ...rest } = result;
    result.segments = segments.slice(0, 40);
  }
  return sendJSON(res, 200, result);
}

/** When the uploader supplied no chapters, derive them from caption pauses. */
export function deriveChapters(segments, { target = 8, minGap = 45 } = {}) {
  if (!segments?.length) return [];
  const total = segments[segments.length - 1].start || 0;
  if (!total) return [];
  const size = Math.max(60, total / target);
  const out = [];
  for (let t = 0; t < total; t += size) {
    const near = segments.reduce((best, s) => (Math.abs(s.start - t) < Math.abs(best.start - t) ? s : best), segments[0]);
    if (out.length && near.start - out[out.length - 1].start < minGap) continue;
    out.push({ start: Math.round(near.start), time: clock(near.start), title: near.text.slice(0, 70) });
  }
  return out;
}
function clock(sec) {
  const s = Math.floor(sec % 60), m = Math.floor(sec / 60) % 60, h = Math.floor(sec / 3600);
  return h ? `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}` : `${m}:${String(s).padStart(2, '0')}`;
}
