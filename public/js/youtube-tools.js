/**
 * YouTube Tools — Transcript + Playlist Lister + Chapter Generator
 * Uses /api/youtube-transcript and /api/youtube-playlist (hybrid)
 * All videos with captions work, playlist lister works for public playlists.
 */
import { esc, downloadBlob, downloadText, mountShell, setOut, toast } from './kit.js';

function extractVideoId(input) {
  if (!input) return null;
  const s = String(input).trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(s)) return s;
  try {
    const u = new URL(s);
    if (u.hostname.includes('youtu.be')) {
      const id = u.pathname.split('/').filter(Boolean)[0];
      if (id) return id;
    }
    if (u.searchParams.get('v')) return u.searchParams.get('v');
    const m = u.pathname.match(/\/(?:embed|v|shorts)\/([a-zA-Z0-9_-]{11})/);
    if (m) return m[1];
  } catch {}
  const m = s.match(/[a-zA-Z0-9_-]{11}/);
  return m ? m[0] : null;
}

export function mountYouTubeTranscript(root, tool) {
  root.innerHTML = '';
  const body = mountShell(root, tool, `
    <div class="field-row" style="margin-top:8px">
      <input id="yt-url" class="field" placeholder="YouTube URL or Video ID (e.g. https://youtube.com/watch?v=dQw4w9WgXcQ)" style="grid-column: span 2">
      <select id="yt-lang" class="sel"><option value="en" selected>English</option><option value="hi">Hindi</option><option value="es">Spanish</option><option value="fr">French</option><option value="de">German</option><option value="ml">Malayalam</option><option value="ta">Tamil</option></select>
      <select id="yt-fmt" class="sel"><option value="text">Plain text</option><option value="srt">SRT</option><option value="vtt">VTT</option><option value="json">JSON</option></select>
    </div>
    <div class="button-row">
      <button class="btn primary" id="run">Get Transcript</button>
      <button class="btn secondary" id="copy">Copy</button>
      <button class="btn ghost" id="dl">Download</button>
      <button class="btn ghost" id="summarize">Summarize with AI</button>
    </div>
    <div id="yt-meta" class="note" style="margin-top:12px">Works for any video that has captions (manual or auto-generated). Uses YouTube's own timedtext + Piped fallback. No API key needed.</div>
    <pre id="tool-out" class="out" style="margin-top:12px;min-height:220px;max-height:50vh"></pre>
    <div id="yt-segments" style="margin-top:12px;max-height:260px;overflow:auto;border:1px solid #e0d5c4;border-radius:10px;padding:8px;display:none"></div>
  `);

  const $ = id => body.querySelector('#' + id);
  let lastResult = null;

  $('run').onclick = async () => {
    const input = $('yt-url').value.trim();
    if (!input) return setOut(body, 'Paste a YouTube URL first.');
    const lang = $('yt-lang').value;
    const fmt = $('yt-fmt').value;
    const vid = extractVideoId(input);
    if (!vid) return setOut(body, 'Invalid YouTube URL or ID.');
    
    setOut(body, `Fetching transcript for ${vid} (${lang})…`);
    $('yt-meta').textContent = 'Contacting YouTube…';
    
    try {
      const r = await fetch('/api/youtube-transcript', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ videoId: vid, lang, format: fmt })
      });
      const j = await r.json();
      if (!r.ok) throw Error(j.error || 'Transcript not found');
      
      lastResult = j;
      let out = '';
      if (fmt === 'srt' && j.srt) out = j.srt;
      else if (fmt === 'vtt' && j.vtt) out = j.vtt;
      else if (fmt === 'json') out = JSON.stringify(j.segments, null, 2);
      else out = j.text;
      
      setOut(body, out);
      $('yt-meta').innerHTML = `
        <b>${esc(j.languageName || j.language)}</b> · ${j.isAutoGenerated ? 'Auto-generated' : 'Manual'} · ${j.count} segments · ${j.duration ? j.duration.toFixed(1) + 's' : ''} · Source: ${esc(j.source)}
        <br>Video: <a href="https://www.youtube.com/watch?v=${esc(j.videoId)}" target="_blank" rel="noopener">youtube.com/watch?v=${esc(j.videoId)}</a>
        <br><small>Tip: Use SRT for subtitles, Text for AI summarization, JSON for processing.</small>
      `;
      
      // Show clickable segments
      const segEl = $('yt-segments');
      segEl.style.display = 'block';
      segEl.innerHTML = j.segments.slice(0, 200).map(s => `
        <div style="padding:6px 8px;border-bottom:1px solid #f0e6d6;display:flex;gap:8px">
          <span style="color:#8a7f72;font-size:11px;min-width:54px">${Math.floor(s.start/60)}:${String(Math.floor(s.start%60)).padStart(2,'0')}</span>
          <span style="flex:1;font-size:13px">${esc(s.text)}</span>
        </div>
      `).join('') + (j.segments.length > 200 ? `<div class="muted" style="padding:8px">… and ${j.segments.length - 200} more segments</div>` : '');
      
    } catch (e) {
      setOut(body, 'Error: ' + e.message + '\n\nTry:\n- Video with captions enabled (check CC button on YouTube)\n- Public video, not private/deleted\n- Different language (try en)\n- Some videos block transcript via IP, try again later');
      $('yt-meta').textContent = 'Failed. ' + e.message;
    }
  };

  $('copy').onclick = async () => {
    const txt = body.querySelector('#tool-out').textContent;
    if (!txt) return toast('Nothing to copy');
    await navigator.clipboard.writeText(txt);
    toast('Copied transcript');
  };

  $('dl').onclick = () => {
    if (!lastResult) return toast('Fetch transcript first');
    const fmt = $('yt-fmt').value;
    const ext = fmt === 'srt' ? 'srt' : fmt === 'vtt' ? 'vtt' : fmt === 'json' ? 'json' : 'txt';
    const content = body.querySelector('#tool-out').textContent;
    downloadText(content, `youtube-${lastResult.videoId}-${lastResult.language}.${ext}`, fmt === 'json' ? 'application/json' : 'text/plain');
  };

  $('summarize').onclick = async () => {
    if (!lastResult) return toast('Get transcript first');
    const text = lastResult.text.slice(0, 15000);
    if (!text) return toast('No transcript text');
    setOut(body, 'Summarizing with AI…');
    try {
      const r = await fetch('/api/ai', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ task: 'summarize', text, extra: 'Summarize this YouTube transcript in bullet points, key takeaways, and timestamps if useful.' })
      });
      const j = await r.json();
      if (!r.ok) throw Error(j.error || 'AI unavailable');
      setOut(body, `TRANSCRIPT:\n${text.slice(0, 2000)}…\n\n--- AI SUMMARY ---\n${j.result || j.text || JSON.stringify(j)}`);
    } catch (e) {
      setOut(body, lastResult.text + '\n\n--- AI Summary failed: ' + e.message + ' ---\nTip: Copy transcript and paste into Google AI Studio (Gemini 1.5 Flash, 1M context) for free summarization.');
    }
  };
}

