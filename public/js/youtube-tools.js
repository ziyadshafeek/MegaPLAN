export function mountYouTubeChapter(root, tool) {
  const body = mountShell(root, tool, `
    <p class="muted">Paste transcript (with timestamps) or YouTube URL to generate chapters for description.</p>
    <textarea id="chap-in" class="input-area" placeholder="Paste transcript or YouTube URL... You can also paste SRT/VTT"></textarea>
    <div class="field-row" style="margin-top:8px">
      <input id="chap-interval" class="num" type="number" value="5" placeholder="Chapter every N minutes">
      <select id="chap-style" class="sel"><option value="youtube">YouTube style (0:00 - Title)</option><option value="md">Markdown</option><option value="srt">SRT chapters</option></select>
    </div>
    <div class="button-row">
      <button class="btn primary" id="run">Generate Chapters</button>
      <button class="btn secondary" id="from-url">From YouTube URL</button>
      <button class="btn ghost" id="copy">Copy</button>
    </div>
    <pre id="tool-out" class="out" style="margin-top:12px;min-height:180px"></pre>
  `);

  const $ = id => body.querySelector('#' + id);

  function generateChaptersFromSegments(segments, intervalMin) {
    // Group by interval
    const intervalSec = intervalMin * 60;
    const chapters = [];
    let current = [];
    let currentStart = 0;
    
    for (const seg of segments) {
      if (seg.start - currentStart >= intervalSec && current.length) {
        // Summarize current chunk (first few words as title)
        const text = current.map(s => s.text).join(' ');
        const title = text.split(' ').slice(0, 6).join(' ') + '...';
        chapters.push({ start: currentStart, title });
        current = [];
        currentStart = seg.start;
      }
      current.push(seg);
    }
    if (current.length) {
      const text = current.map(s => s.text).join(' ');
      const title = text.split(' ').slice(0, 6).join(' ') + '...';
      chapters.push({ start: currentStart, title });
    }
    return chapters;
  }

  $('run').onclick = async () => {
    const input = $('chap-in').value.trim();
    if (!input) return setOut(body, 'Paste transcript or URL');
    const interval = Number($('chap-interval').value) || 5;
    const style = $('chap-style').value;
    
    // Try to parse as SRT/VTT with timestamps
    const timeRegex = /(\d+):(\d+):?(\d+)?/g;
    // For simplicity, if input contains " --> " it's SRT/VTT
    if (input.includes('-->') || /^\d+\n\d+:/m.test(input)) {
      // Parse SRT
      const blocks = input.split(/\n\n+/);
      const segs = [];
      for (const b of blocks) {
        const m = b.match(/(\d+):(\d+):(\d+)[,\.](\d+)\s+-->\s+(\d+):(\d+):(\d+)[,\.](\d+)/);
        if (m) {
          const start = parseInt(m[1])*3600 + parseInt(m[2])*60 + parseInt(m[3]) + parseInt(m[4])/1000;
          const text = b.split('\n').slice(2).join(' ').trim();
          if (text) segs.push({ start, text });
        }
      }
      if (segs.length) {
        const chapters = generateChaptersFromSegments(segs.map(s => ({ start: s.start, text: s.text })), interval);
        let out = '';
        if (style === 'youtube') out = chapters.map(c => `${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')} - ${c.title}`).join('\n');
        else if (style === 'md') out = chapters.map(c => `- [${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')}] ${c.title}`).join('\n');
        else out = chapters.map((c,i) => `${i+1}\n${new Date(c.start*1000).toISOString().substr(11,8)},000 --> ${new Date((c.start+30)*1000).toISOString().substr(11,8)},000\n${c.title}\n`).join('\n');
        return setOut(body, out);
      }
    }
    
    // If input is YouTube URL, fetch transcript first
    const vid = extractVideoId(input);
    if (vid) {
      $('from-url').click();
      return;
    }
    
    // Otherwise treat as plain text and split into chapters by sentences
    const sentences = input.split(/[.!?]+/).filter(s => s.trim().length > 20);
    const wordsPerChapter = 150;
    const chapters = [];
    let currentWords = 0;
    let currentText = '';
    let startTime = 0;
    const avgWpm = 150;
    
    for (const sent of sentences) {
      const w = sent.trim().split(/\s+/).length;
      currentWords += w;
      currentText += sent + '. ';
      if (currentWords >= wordsPerChapter) {
        const title = currentText.split(' ').slice(0, 7).join(' ') + '...';
        chapters.push({ start: startTime, title });
        startTime += (currentWords / avgWpm) * 60;
        currentWords = 0;
        currentText = '';
      }
    }
    if (currentText) {
      const title = currentText.split(' ').slice(0, 7).join(' ') + '...';
      chapters.push({ start: startTime, title });
    }
    
    let out = '';
    if (style === 'youtube') out = chapters.map(c => `${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')} - ${c.title}`).join('\n');
    else if (style === 'md') out = chapters.map(c => `- [${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')}] ${c.title}`).join('\n');
    else out = chapters.map((c,i) => `${i+1}\n${new Date(c.start*1000).toISOString().substr(11,8)},000 --> ${new Date((c.start+30)*1000).toISOString().substr(11,8)},000\n${c.title}\n`).join('\n');
    
    setOut(body, out || 'Could not generate chapters. Try pasting transcript with timestamps or YouTube URL.');
  };

  $('from-url').onclick = async () => {
    const input = $('chap-in').value.trim();
    const vid = extractVideoId(input);
    if (!vid) return setOut(body, 'Paste YouTube URL in the box above, then click From YouTube URL');
    
    setOut(body, 'Fetching transcript for chapter generation…');
    try {
      const r = await fetch('/api/youtube-transcript', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ videoId: vid, lang: 'en', format: 'json' })
      });
      const j = await r.json();
      if (!r.ok) throw Error(j.error);
      
      const interval = Number($('chap-interval').value) || 5;
      const style = $('chap-style').value;
      const chapters = generateChaptersFromSegments(j.segments, interval);
      
      let out = '';
      if (style === 'youtube') out = chapters.map(c => `${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')} - ${c.title}`).join('\n');
      else if (style === 'md') out = chapters.map(c => `- [${Math.floor(c.start/60)}:${String(Math.floor(c.start%60)).padStart(2,'0')}] ${c.title}`).join('\n');
      else out = chapters.map((c,i) => `${i+1}\n${new Date(c.start*1000).toISOString().substr(11,8)},000 --> ${new Date((c.start+30)*1000).toISOString().substr(11,8)},000\n${c.title}\n`).join('\n');
      
      setOut(body, `Chapters for https://youtube.com/watch?v=${vid}\n\n` + out + `\n\n---\nGenerated from ${j.count} transcript segments`);
    } catch (e) {
      setOut(body, 'Error: ' + e.message);
    }
  };

  $('copy').onclick = async () => {
    const txt = body.querySelector('#tool-out').textContent;
    if (!txt) return toast('Nothing to copy');
    await navigator.clipboard.writeText(txt);
    toast('Copied chapters');
  };
}
